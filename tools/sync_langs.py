"""Sign Reader -> data/langs.js : languages (name, font, sample words, look-alikes) and where each one is written.

    python tools/sync_langs.py            # reads ..\\script-identifier-geoguessr\\index.html

Re-run it after changing the languages of Sign Reader. Plates and bollards need no copy: the page reads them from
the plate-trainer and bollards-trainer repos next to this one (same site on GitHub Pages, sibling folders locally).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "script-identifier-geoguessr" / "index.html"


def js_obj(txt):
    """Small JS object literal {a:"x", b:"y z"} -> dict (keys unquoted, string values only)."""
    return dict(re.findall(r'(\w+)\s*:\s*"([^"]*)"', txt))


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    html = src.read_text(encoding="utf-8")
    fonts = {k: v.strip('"') for k, v in re.findall(r"(\w+)\s*:\s*(\"[^\"]*\")", re.search(r"const F = \{(.*?)\};", html, re.S).group(1).replace("'", '"'))}
    cc = js_obj(re.search(r"const LANG_CC = \{(.*?)\};", html, re.S).group(1))
    langs, seen = [], set()
    for m in re.finditer(r'\{id:"(\w+)",name:"([^"]+)",place:"([^"]*)",fam:"([\w-]+)",font:(F\.(\w+)|"([^"]*)")(.*?)\}(?=,?\s*\n)', html, re.S):
        lid, name, place, fam = m.group(1), m.group(2), m.group(3), m.group(4)
        font = fonts.get(m.group(6)) if m.group(6) else m.group(7)
        rest = m.group(8)
        s = re.search(r"\bs:(\[.*?\])", rest, re.S)
        conf = re.search(r"\bconf:(\[.*?\])", rest, re.S)
        if lid in seen or not s:
            continue
        seen.add(lid)
        langs.append({"id": lid, "name": name, "place": place, "fam": fam, "font": font.replace("'", "").replace('"', ""),
                      "s": json.loads(s.group(1)), "conf": json.loads(conf.group(1)) if conf else [],
                      "cc": (cc.get(lid) or "").split()})
    ids = {l["id"] for l in langs}
    for l in langs:                                   # look-alikes both ways, as Sign Reader does
        for c in l["conf"]:
            o = next((x for x in langs if x["id"] == c), None)
            if o and l["id"] not in o["conf"]:
                o["conf"].append(l["id"])
    for l in langs:
        l["conf"] = sorted({c for c in l["conf"] if c in ids and c != l["id"]})
    out = ROOT / "data" / "langs.js"
    body = ",\n".join(json.dumps(l, ensure_ascii=False, separators=(",", ":")) for l in langs)
    out.write_text("// Generated by tools/sync_langs.py from Sign Reader, do not edit by hand.\nwindow.CF_LANGS = [\n" + body + "\n];\n",
                   encoding="utf-8", newline="\n")
    nocc = [l["id"] for l in langs if not l["cc"]]
    print(f"{len(langs)} languages -> {out.relative_to(ROOT)}" + (f" ; no country for: {' '.join(nocc)}" if nocc else ""))


if __name__ == "__main__":
    main()
